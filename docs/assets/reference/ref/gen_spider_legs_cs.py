"""Write remake/src/OpenSimAnt.Data/SpiderLegs.cs: the C# port of the spider's leg and fang drawing routines
f_04c44 / f_04666 as move-to / line-to programs per heading (from tools/re/polylines.py's analysis of the
code). The programs only name T-table offsets; the coordinates come from the player's own EXE at runtime.

python gen_spider_legs_cs.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 're', 'build', 'spider_legs.json')
OUT = os.path.join(HERE, '..', '..', 'remake', 'src', 'OpenSimAnt.Data', 'SpiderLegs.cs')
REG = {None: 0, 'si': 1, 'di': 2}


def term(t):
    base, k, table, reg, sign = t
    return f'new({k}, {-1 if table is None else table}, {REG[reg]}, {sign})'


def main():
    d = json.load(open(SRC))
    lines = ['// Generated by tools/ref/gen_spider_legs_cs.py: a port of the drawing routines f_04c44 (legs) and',
             '// f_04666 (fangs). Each op is a move-to or line-to whose x / y is the spider position + k + sign *',
             '// T[table + register] (register 0 none, 1 si, 2 di).',
             'namespace OpenSimAnt.Data;', '',
             'public static partial class SpiderLegs', '{']
    for name, field in (('f_04c44', 'Legs'), ('f_04666', 'Fangs')):
        lines.append(f'    /// <summary>{name}, per heading 0..7.</summary>')
        lines.append(f'    public static readonly Op[][] {field} =')
        lines.append('    {')
        for case in d[name]['cases']:
            ops = ', '.join(f'new({"true" if op == "line" else "false"}, {term(x)}, {term(y)})' for op, x, y in case)
            lines.append(f'        new Op[] {{ {ops} }},')
        lines.append('    };')
        lines.append('')
    lines[-1] = '}'
    open(OUT, 'w', newline='\n').write('\n'.join(lines) + '\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
